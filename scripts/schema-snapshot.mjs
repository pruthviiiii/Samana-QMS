// Writes db/schema.sql: the live definition of every table, constraint, index,
// view, trigger and function in the qms schema, plus the migrations that
// produced it. Migrations stay the history; this file is the current state.
// tests/schema.test.ts fails when the file and the migrated database differ.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
// Function bodies applied from CRLF checkouts carry carriage returns; the
// snapshot is normalised so it reads the same from any client or platform.
const lf = (text) => String(text).replace(/\r\n?/g, '\n').trim();
export async function snapshot(run) {
  const lines = ['-- Generated by scripts/schema-snapshot.mjs. Do not edit.'];
  const migrations = await run('SELECT name FROM qms.migrations ORDER BY name');
  lines.push('-- Applied migrations: ' + migrations.map((m) => m.name).join(', '));
  const tables = await run(
    "SELECT table_name FROM information_schema.tables WHERE table_schema='qms' AND table_type='BASE TABLE' ORDER BY table_name",
  );
  for (const { table_name } of tables) {
    lines.push('', `-- table qms.${table_name}`);
    const columns = await run(
      "SELECT column_name,udt_name,is_nullable,column_default FROM information_schema.columns WHERE table_schema='qms' AND table_name=$1 ORDER BY ordinal_position",
      [table_name],
    );
    for (const c of columns)
      lines.push(
        `  ${c.column_name} ${c.udt_name}${c.is_nullable === 'NO' ? ' not null' : ''}${c.column_default ? ' default ' + c.column_default : ''}`,
      );
    const constraints = await run(
      "SELECT conname,pg_get_constraintdef(oid) def FROM pg_constraint WHERE conrelid=('qms.'||quote_ident($1))::regclass ORDER BY conname",
      [table_name],
    );
    for (const k of constraints) lines.push(`  constraint ${k.conname} ${k.def}`);
    const indexes = await run(
      "SELECT indexname,indexdef FROM pg_indexes WHERE schemaname='qms' AND tablename=$1 ORDER BY indexname",
      [table_name],
    );
    for (const i of indexes) lines.push(`  ${i.indexdef}`);
  }
  const sequences = await run(
    "SELECT sequence_name FROM information_schema.sequences WHERE sequence_schema='qms' ORDER BY sequence_name",
  );
  for (const s of sequences) lines.push('', `-- sequence qms.${s.sequence_name}`);
  const views = await run(
    "SELECT viewname,pg_get_viewdef(('qms.'||quote_ident(viewname))::regclass,true) def FROM pg_views WHERE schemaname='qms' ORDER BY viewname",
  );
  for (const v of views)
    lines.push('', `-- view qms.${v.viewname}`, lf(v.def));
  const triggers = await run(
    "SELECT tgname,pg_get_triggerdef(oid) def FROM pg_trigger WHERE tgrelid IN (SELECT oid FROM pg_class WHERE relnamespace='qms'::regnamespace) AND NOT tgisinternal ORDER BY tgname",
  );
  for (const t of triggers) lines.push('', `-- trigger ${t.tgname}`, lf(t.def));
  const functions = await run(
    "SELECT p.proname,pg_get_function_identity_arguments(p.oid) args,pg_get_functiondef(p.oid) def FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='qms' ORDER BY p.proname,args",
  );
  for (const f of functions)
    lines.push('', `-- function qms.${f.proname}(${f.args})`, lf(f.def));
  return lines.join('\n') + '\n';
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { open } = await import('./db.mjs');
  const db = await open(process.env.DATABASE_URL);
  try {
    const text = await snapshot(db.query);
    const target = new URL('../db/schema.sql', import.meta.url);
    await writeFile(target, text);
    console.log(`Wrote ${fileURLToPath(target)} (${text.length} bytes).`);
  } finally {
    await db.end();
  }
}
